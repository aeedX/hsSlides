-- | Скрипт редактора: перетаскивание, маркеры размера, горячие клавиши.
-- Все изменения отправляются на сервер (POST /act), страница перезагружается.
editorJs :: String
editorJs = unlines
  [ "(function(){"
  , "var stage=document.getElementById('stage');"
  , "var wrap=document.getElementById('wrap');"
  , "var body=document.body;"
  , "var cur=parseInt(body.getAttribute('data-cur'),10)||0;"
  , "var count=parseInt(body.getAttribute('data-count'),10)||1;"
  , "var scale=1;"
  , "var drag=null;"
  , "var dirty=false;"
  , "var pf=document.getElementById('pf');"
  , "var bf=document.getElementById('bgf');"
  , "function fit(){"
  , "  var w=wrap.clientWidth||960;"
  , "  scale=Math.min(1.25,w/960);"
  , "  stage.style.transform='scale('+scale+')';"
  , "  wrap.style.height=Math.round(540*scale)+'px';"
  , "}"
  , "function post(p){"
  , "  return fetch('/act',{method:'POST',headers:{'Content-Type':'application/x-www-form-urlencoded'},body:new URLSearchParams(p).toString()}).then(function(){location.reload();});"
  , "}"
  , "function num(el,k){return parseInt(el.getAttribute('data-'+k),10)||0;}"
  , "function box(el){return {x:num(el,'x'),y:num(el,'y'),w:num(el,'w'),h:num(el,'h')};}"
  , "function place(el,b){el.style.left=b.x+'px';el.style.top=b.y+'px';el.style.width=b.w+'px';el.style.height=b.h+'px';}"
  , "stage.addEventListener('mousedown',function(e){"
  , "  if(e.button!==0)return;"
  , "  if(dirty&&pf){dirty=false;e.preventDefault();pf.submit();return;}"
  , "  var t=e.target;"
  , "  var sel=document.getElementById('sel');"
  , "  var hd=t.closest('.h');"
  , "  var el=hd?null:t.closest('.el');"
  , "  var d;"
  , "  if(hd&&sel){"
  , "    d={id:sel.getAttribute('data-id'),dir:hd.getAttribute('data-d'),b:box(sel),min:num(sel,'min'),node:null};"
  , "    d.node=stage.querySelector('.el[data-id=\"'+d.id+'\"]');"
  , "  }else if(el){"
  , "    d={id:el.getAttribute('data-id'),dir:'move',b:box(el),min:10,node:el};"
  , "  }else{"
  , "    location.href='/deselect';"
  , "    return;"
  , "  }"
  , "  d.x0=e.clientX;d.y0=e.clientY;d.sel=sel;d.moved=false;d.nb=null;"
  , "  drag=d;"
  , "  e.preventDefault();"
  , "});"
  , "document.addEventListener('mousemove',function(e){"
  , "  if(!drag)return;"
  , "  var dx=(e.clientX-drag.x0)/scale;"
  , "  var dy=(e.clientY-drag.y0)/scale;"
  , "  if(!drag.moved&&Math.abs(dx)+Math.abs(dy)<3)return;"
  , "  drag.moved=true;"
  , "  var b=drag.b,m=drag.min,r=drag.dir;"
  , "  var n={x:b.x,y:b.y,w:b.w,h:b.h};"
  , "  if(r==='move'){n.x=b.x+dx;n.y=b.y+dy;}"
  , "  else{"
  , "    if(r.indexOf('e')>=0)n.w=Math.max(m,b.w+dx);"
  , "    if(r.indexOf('s')>=0)n.h=Math.max(m,b.h+dy);"
  , "    if(r.indexOf('w')>=0){n.w=Math.max(m,b.w-dx);n.x=b.x+b.w-n.w;}"
  , "    if(r.indexOf('n')>=0){n.h=Math.max(m,b.h-dy);n.y=b.y+b.h-n.h;}"
  , "  }"
  , "  n.x=Math.round(n.x);n.y=Math.round(n.y);n.w=Math.round(n.w);n.h=Math.round(n.h);"
  , "  drag.nb=n;"
  , "  if(drag.node)place(drag.node,n);"
  , "  if(drag.sel&&drag.sel.getAttribute('data-id')===drag.id)place(drag.sel,n);"
  , "});"
  , "document.addEventListener('mouseup',function(){"
  , "  if(!drag)return;"
  , "  var d=drag;drag=null;"
  , "  if(d.moved&&d.nb){"
  , "    post({a:'geom',id:d.id,x:d.nb.x,y:d.nb.y,w:d.nb.w,h:d.nb.h});"
  , "  }else if(d.dir==='move'){"
  , "    var s=document.getElementById('sel');"
  , "    if(!s||s.getAttribute('data-id')!==d.id)location.href='/select/'+d.id;"
  , "  }"
  , "});"
  , "stage.addEventListener('dblclick',function(){"
  , "  var t=document.getElementById('f-text');"
  , "  if(t){t.focus();t.select();}"
  , "});"
  , "document.addEventListener('keydown',function(e){"
  , "  var tag=e.target&&e.target.tagName;"
  , "  if(tag==='INPUT'||tag==='TEXTAREA'||tag==='SELECT')return;"
  , "  var k=e.key;"
  , "  var mod=e.ctrlKey||e.metaKey;"
  , "  var has=!!document.getElementById('sel');"
  , "  if(mod){"
  , "    if(k==='z'||k==='Z'){e.preventDefault();post({a:e.shiftKey?'redo':'undo'});}"
  , "    else if(k==='y'||k==='Y'){e.preventDefault();post({a:'redo'});}"
  , "    else if((k==='d'||k==='D')&&has){e.preventDefault();post({a:'dup'});}"
  , "    return;"
  , "  }"
  , "  if((k==='Delete'||k==='Backspace')&&has){e.preventDefault();post({a:'del'});}"
  , "  else if(k.indexOf('Arrow')===0&&has){"
  , "    e.preventDefault();"
  , "    var st=e.shiftKey?20:2;"
  , "    var dx=k==='ArrowLeft'?-st:(k==='ArrowRight'?st:0);"
  , "    var dy=k==='ArrowUp'?-st:(k==='ArrowDown'?st:0);"
  , "    post({a:'nudge',dx:dx,dy:dy});"
  , "  }"
  , "  else if(k==='Escape'){location.href='/deselect';}"
  , "  else if(k==='PageDown'&&cur<count-1){e.preventDefault();location.href='/slide/'+(cur+2);}"
  , "  else if(k==='PageUp'&&cur>0){e.preventDefault();location.href='/slide/'+cur;}"
  , "});"
  , "if(pf){"
  , "  pf.addEventListener('input',function(){dirty=true;});"
  , "  pf.addEventListener('change',function(){dirty=false;pf.submit();});"
  , "}"
  , "if(bf)bf.addEventListener('change',function(){bf.submit();});"
  , "window.addEventListener('resize',fit);"
  , "fit();"
  , "})();"
  ]

