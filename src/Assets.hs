-- | Скрипт показа: стрелки, пробел, щелчок, Home/End, F — полный экран.
showJs :: String
showJs = unlines
  [ "(function(){"
  , "var slides=[].slice.call(document.querySelectorAll('.slide'));"
  , "var n=slides.length;"
  , "var cur=0;"
  , "var back=document.body.getAttribute('data-esc');"
  , "var hud=document.getElementById('hud');"
  , "function fit(){"
  , "  var s=Math.min(window.innerWidth/960,window.innerHeight/540);"
  , "  var ox=(window.innerWidth-960*s)/2;"
  , "  var oy=(window.innerHeight-540*s)/2;"
  , "  slides.forEach(function(el){el.style.transform='translate('+ox+'px,'+oy+'px) scale('+s+')';});"
  , "}"
  , "function go(i){"
  , "  cur=Math.max(0,Math.min(n-1,i));"
  , "  slides.forEach(function(el,k){el.className='slide'+(k===cur?' on':'');});"
  , "  hud.textContent=(cur+1)+' / '+n;"
  , "  if(history.replaceState)history.replaceState(null,'','#'+(cur+1));"
  , "}"
  , "function full(){"
  , "  if(document.fullscreenElement){document.exitFullscreen();}"
  , "  else if(document.documentElement.requestFullscreen){document.documentElement.requestFullscreen();}"
  , "}"
  , "document.addEventListener('keydown',function(e){"
  , "  var k=e.key;"
  , "  if(k==='ArrowRight'||k==='ArrowDown'||k==='PageDown'||k===' '||k==='Enter'){e.preventDefault();go(cur+1);}"
  , "  else if(k==='ArrowLeft'||k==='ArrowUp'||k==='PageUp'||k==='Backspace'){e.preventDefault();go(cur-1);}"
  , "  else if(k==='Home'){go(0);}"
  , "  else if(k==='End'){go(n-1);}"
  , "  else if(k==='f'||k==='F'){full();}"
  , "  else if(k==='Escape'&&back&&!document.fullscreenElement){location.href=back;}"
  , "});"
  , "document.addEventListener('click',function(e){go(e.clientX<window.innerWidth/3?cur-1:cur+1);});"
  , "window.addEventListener('resize',fit);"
  , "fit();"
  , "go((parseInt(location.hash.slice(1),10)||1)-1);"
  , "})();"
  ]
